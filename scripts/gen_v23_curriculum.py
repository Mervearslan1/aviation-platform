def esc(s: str) -> str:
    return s.replace("'", "''")


def q(s: str) -> str:
    return "'" + esc(s) + "'"


def cfg(d: dict) -> str:
    return q(json.dumps(d, ensure_ascii=False, separators=(",", ":"))) + "::jsonb"


def opts(correct: str, wrongs: list[str], rot: int) -> tuple[list[str], str]:
    items = [correct, *wrongs[:2]]
    r = rot % 3
    items = items[r:] + items[:r]
    return items, correct


def listen(stage, slug, title, desc, html, prompt, question, correct, wrongs, rot, extra=None):
    options, c = opts(correct, wrongs, rot)
    d = {"stage": stage, "promptText": prompt, "question": question, "options": options, "correctOption": c}
    if extra:
        d.update(extra)
    return ("LISTEN", slug, title, desc, html, d)


def speak(stage, slug, title, desc, html, prompt, expected, accepted, reply):
    return ("SPEAK", slug, title, desc, html, {
        "stage": stage,
        "promptText": prompt,
        "expectedPhrase": expected,
        "acceptedPhrases": accepted,
        "replyText": reply,
    })


def scene(stage, slug, title, desc, html, situation, correct, wrongs, rot, expected, reply):
    options, c = opts(correct, wrongs, rot)
    return ("SCENARIO", slug, title, desc, html, {
        "stage": stage,
        "situation": situation,
        "options": options,
        "correctOption": c,
        "expectedPhrase": expected,
        "replyText": reply,
    })


def content(stage, slug, title, desc, html):
    return ("CONTENT", slug, title, desc, html, {"stage": stage})


def live(stage, slug, title, desc, html):
    return ("LIVE_PRACTICE", slug, title, desc, html, {
        "stage": stage,
        "platform": "IVAO",
        "url": "https://www.ivao.aero",
        "instruction": "IVAO'da dinle veya sektor dene. En az bir cagri-cevap.",
    })


