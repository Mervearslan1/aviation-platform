def emit(path_slug: str, rows: list, start_order: int) -> list[str]:
    lines = []
    order = start_order
    for kind, slug, title, desc, html, conf in rows:
        lines.append(
            "INSERT INTO learning_steps (path_id, title, slug, description, step_type, content_html, configuration, order_index, required, status)\n"
            f"SELECT id, {q(title)}, {q(slug)}, {q(desc)}, {q(kind)}, {q(html)}, {cfg(conf)}, {order}, TRUE, 'PUBLISHED' "
            f"FROM learning_paths WHERE slug = {q(path_slug)}\n"
            f"AND NOT EXISTS (SELECT 1 FROM learning_steps WHERE slug = {q(slug)});\n"
        )
        order += 1
    return lines


